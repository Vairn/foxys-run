static void plotPixel(
	tBitMap *pBm, WORD wX, WORD wY, UBYTE ubColor,
	UWORD uwMaxX, UWORD uwPlaneRow
) {
	if(wX < 0 || wY < 0 || (UWORD)wX >= uwMaxX || (UWORD)wY >= pBm->Rows) {
		return;
	}
	ULONG ulRow = (ULONG)wY * pBm->BytesPerRow;
	UBYTE ubBit = (UBYTE)(0x80 >> (wX & 7));
	UBYTE ubOffsX = (UBYTE)((UWORD)wX >> 3);
	for(UBYTE ubPlane = 0; ubPlane < pBm->Depth; ++ubPlane) {
		UBYTE *p = (UBYTE *)pBm->Planes[0] + ulRow + (ULONG)ubPlane * uwPlaneRow + ubOffsX;
		if(ubColor & (UBYTE)(1 << ubPlane)) {
			*p |= ubBit;
		}
		else {
			*p &= (UBYTE)~ubBit;
		}
	}
}

UWORD fontTextWidth(const char *sz, UBYTE ubScale) {
	UWORD uw = 0;
	while(*sz++) {
		uw += FONT_ADV * ubScale;
	}
	return uw ? (UWORD)(uw - ubScale) : 0;
}

void fontDrawChar(
	tBitMap *pBm, WORD wX, WORD wY, char c, UBYTE ubColor, UBYTE ubScale
) {
	if(c >= 'a' && c <= 'z') {
		c = (char)(c - 'a' + 'A');
	}
	if(c < ' ' || c > 'Z') {
		c = ' ';
	}
	if(!ubScale) {
		ubScale = 1;
	}
	UWORD uwMaxX = (UWORD)(bitmapGetByteWidth(pBm) << 3);
	UWORD uwPlaneRow = pBm->BytesPerRow / pBm->Depth;
	const UBYTE *pGlyph = s_pFont[c - ' '];
	for(UBYTE row = 0; row < FONT_H; ++row) {
		UBYTE ubBits = pGlyph[row];
		for(UBYTE col = 0; col < FONT_W; ++col) {
			if(ubBits & (0x10 >> col)) {
				WORD wPx = wX + (WORD)col * ubScale;
				WORD wPy = wY + (WORD)row * ubScale;
				for(UBYTE sy = 0; sy < ubScale; ++sy) {
					for(UBYTE sx = 0; sx < ubScale; ++sx) {
						plotPixel(pBm, wPx + sx, wPy + sy, ubColor, uwMaxX, uwPlaneRow);
					}
				}
			}
		}
	}
}

void fontDrawText(
	tBitMap *pBm, WORD wX, WORD wY, const char *sz, UBYTE ubColor, UBYTE ubScale
) {
	while(*sz) {
		fontDrawChar(pBm, wX, wY, *sz++, ubColor, ubScale);
		wX += FONT_ADV * ubScale;
	}
}
